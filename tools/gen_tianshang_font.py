OUT_DIR = os.path.join(os.path.dirname(__file__), "../main")

# Complete Chinese characters and symbols for Tianshang Gacha
TIANSHANG_CHARS = (
    # 核心界面与抽卡名词
    "天赏奇赏凡赏祥瑞抽卡抽奖神石鉴华单抽十连五十连"
    "天赏石月泉衔碧丹阙霓天奇赏石风筝轻容染螺黛染照夜花拥香雾映月荧霓旌摇星落花旋归初凝丹"
    # 统计与面板标签
    "累计抽数当前保底保底次数直出祥瑞累计天赏首次天赏首次祥瑞当前称号最佳保底"
    "总计消耗按键确认返回重置恭喜获得已获得获得个颗份次抽纹玉代币元电量本期奖池"
    # 称号库 (11档称号完整字符)
    "初游江湖闲云自在放歌清宵凭栏听雨把酒临风卧看千山一醉轻王侯秋水不染尘乘风登玉京缥缈云流鹤上仙捧日揽月摘星辰"
    # 提示与状态
    "上键下键长按短按单次连抽历史统计详细统计背包规则说明暂无数据清空重置成功战报核心基础记录命中结算开内出预览"
    # 扩展常用字与系统字
    "绝品硬必升约任停内存冲分创刷务动化区可启复外失始字屏建张待恢复意擦时未止法紧继续缓缩节设败超配除音等"
    # 标点符号与特殊几何按键指示图形
    "•·★※×：，。！？（）[]【】▲▼●≈"
)

def find_font():
    for p in FONT_PATHS:
        if os.path.exists(p):
            return p
    return None

def pack_bits(vals, bpp):
    out = bytearray()
    acc = 0
    nbits = 0
    for v in vals:
        acc = (acc << bpp) | (v & ((1 << bpp) - 1))
        nbits += bpp
        while nbits >= 8:
            nbits -= 8
            out.append((acc >> nbits) & 0xFF)
    if nbits:
        out.append((acc << (8 - nbits)) & 0xFF)
    return bytes(out)

def render_glyph(font, ch, ascent, bpp):
    adv_w = int(round(font.getlength(ch) * 16))
    bbox = font.getbbox(ch)
    if bbox is None:
        return b"", 0, 0, 0, 0, adv_w
    x0, y0, x1, y1 = bbox
    w, h = x1 - x0, y1 - y0
    if w <= 0 or h <= 0:
        return b"", 0, 0, 0, 0, adv_w

    img = Image.new("L", (w, h), 0)
    ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255)
    shift = 8 - bpp
    vals = [p >> shift for p in img.getdata()]
    return pack_bits(vals, bpp), w, h, x0, ascent - y1, adv_w

def gen_font(font_path, size, bpp, out_path, font_name):
    font = ImageFont.truetype(font_path, size)
    ascent, descent = font.getmetrics()

    ascii_chars = [chr(c) for c in range(0x20, 0x7F)]
    cjk_chars = sorted([c for c in set(TIANSHANG_CHARS) if ord(c) >= 128])
    all_chars = ascii_chars + cjk_chars

    bitmap = bytearray()
    dscs = [(0, 0, 0, 0, 0, 0)] # ID 0 reserved

    for ch in all_chars:
        bm, bw, bh, ox, oy, aw = render_glyph(font, ch, ascent, bpp)
        dscs.append((len(bitmap), aw, bw, bh, ox, oy))
        bitmap += bm

    ascii_gid_start = 1
    cjk_gid_start = 1 + len(ascii_chars)

    # Build CJK unicode offset list
    # Split into groups when gap between code points > 500 or code point span > 0xFFFF
    cjk_groups = []
    for ch in cjk_chars:
        if not cjk_groups or (ord(ch) - ord(cjk_groups[-1][-1]) > 500) or (ord(ch) - ord(cjk_groups[-1][0]) > 0xFFFF):
            cjk_groups.append([])
        cjk_groups[-1].append(ch)

    L = []
    L.append(f'// Generated by tools/gen_tianshang_font.py; size={size}px bpp={bpp}')
    L.append('#include "lvgl.h"')
    L.append('')
    L.append('static const uint8_t glyph_bitmap[] = {')
    for i in range(0, len(bitmap), 16):
        chunk = bitmap[i:i+16]
        L.append('    ' + ', '.join(f'0x{b:02X}' for b in chunk) + ',')
    L.append('};')
    L.append('')
    L.append('static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {')
    for (bi, aw, bw, bh, ox, oy) in dscs:
        L.append(f'    {{.bitmap_index = {bi}, .adv_w = {aw}, .box_w = {bw}, .box_h = {bh}, .ofs_x = {ox}, .ofs_y = {oy}}},')
    L.append('};')
    L.append('')

    for idx, grp in enumerate(cjk_groups):
        grp_start = ord(grp[0])
        offs = [ord(c) - grp_start for c in grp]
        L.append(f'static const uint16_t unicode_list_{idx}[] = {{')
        for i in range(0, len(offs), 12):
            chunk = offs[i:i+12]
            L.append('    ' + ', '.join(f'0x{o:04X}' for o in chunk) + ',')
        L.append('};')
        L.append('')

    L.append('static const lv_font_fmt_txt_cmap_t cmaps[] = {')
    L.append('    {')
    L.append(f'        .range_start = 32, .range_length = {len(ascii_chars)}, .glyph_id_start = {ascii_gid_start},')
    L.append('        .unicode_list = NULL, .glyph_id_ofs_list = NULL, .list_length = 0,')
    L.append('        .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY')
    L.append('    },')

    cur_gid = cjk_gid_start
    for idx, grp in enumerate(cjk_groups):
        grp_start = ord(grp[0])
        grp_len = ord(grp[-1]) - grp_start + 1
        L.append('    {')
        L.append(f'        .range_start = {grp_start}, .range_length = {grp_len}, .glyph_id_start = {cur_gid},')
        L.append(f'        .unicode_list = unicode_list_{idx}, .glyph_id_ofs_list = NULL, .list_length = {len(grp)},')
        L.append('        .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY')
        L.append('    },')
        cur_gid += len(grp)

    L.append('};')
    L.append('')

    L.append('static const lv_font_fmt_txt_dsc_t font_dsc = {')
    L.append('    .glyph_bitmap = glyph_bitmap,')
    L.append('    .glyph_dsc = glyph_dsc,')
    L.append('    .cmaps = cmaps,')
    L.append('    .kern_dsc = NULL,')
    L.append('    .kern_scale = 0,')
    L.append(f'    .cmap_num = {1 + len(cjk_groups)},')
    L.append(f'    .bpp = {bpp},')
    L.append('    .kern_classes = 0,')
    L.append('    .bitmap_format = 0,')
    L.append('};')
    L.append('')

    L.append(f'const lv_font_t {font_name} = {{')
    L.append('    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,')
    L.append('    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,')
    L.append(f'    .line_height = {ascent + descent},')
    L.append(f'    .base_line = {descent},')
    L.append('    .subpx = LV_FONT_SUBPX_NONE,')
    L.append('    .underline_position = -2,')
    L.append('    .underline_thickness = 1,')
    L.append('    .dsc = &font_dsc,')
    L.append('    .fallback = NULL,')
    L.append('    .user_data = NULL,')
    L.append('};')
    L.append('')

    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(L))
    print(f"Generated {out_path}: {len(all_chars)} glyphs, {len(bitmap)} bytes bitmap, line_height={ascent+descent}")

def main():
    font_path = find_font()
    if not font_path:
        sys.exit("Error: No suitable TrueType font found.")
    print(f"Using font: {font_path}")
    os.makedirs(OUT_DIR, exist_ok=True)
    gen_font(font_path, 14, 4, os.path.join(OUT_DIR, "font_tianshang_14.c"), "font_tianshang_14")
    gen_font(font_path, 20, 4, os.path.join(OUT_DIR, "font_tianshang_20.c"), "font_tianshang_20")

if __name__ == "__main__":
    main()
